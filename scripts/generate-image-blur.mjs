import { readdir, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'

const roots = ['public/showcase', 'public/images']
const extensions = new Set(['.webp', '.jpg', '.jpeg', '.png', '.avif'])

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    const fullPath = path.join(directory, entry.name)
    if (entry.isDirectory()) {
      files.push(...await walk(fullPath))
      continue
    }

    if (extensions.has(path.extname(entry.name).toLowerCase())) {
      files.push(fullPath)
    }
  }

  return files
}

const files = (await Promise.all(roots.map((root) => walk(root)))).flat().sort()
const blurData = {}

for (const file of files) {
  const info = await stat(file)
  if (info.size === 0) continue

  try {
    const buffer = await sharp(file)
      .rotate()
      .resize(16, 16, { fit: 'inside', withoutEnlargement: true })
      .webp({ quality: 20 })
      .toBuffer()
    const publicPath = `/${file.slice('public/'.length).split(path.sep).join('/')}`
    blurData[publicPath] = `data:image/webp;base64,${buffer.toString('base64')}`
  } catch (error) {
    console.warn(`skip ${file}: ${error instanceof Error ? error.message : error}`)
  }
}

const lines = Object.entries(blurData).map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
const source = `/* Generated by scripts/generate-image-blur.mjs. Do not edit by hand. */\nexport const IMAGE_BLUR_DATA = {\n${lines.join('\n')}\n} as const\n`

await writeFile(new URL('../src/lib/image-blur-data.ts', import.meta.url), source)
console.log(`wrote ${Object.keys(blurData).length} blur placeholders`)
